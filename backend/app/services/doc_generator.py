import os
import re
from typing import List, Dict, Any
from app.services.parser.tree_sitter_parser import ParsedFileInfo
from app.models.entities import Repository

class DocumentationGenerator:
    @classmethod
    def generate_all_docs(
        cls,
        repo: Repository,
        parsed_files: List[ParsedFileInfo]
    ) -> List[Dict[str, str]]:
        """
        Generates production-grade documentation tailored strictly to real repository files.
        """
        docs = [
            {
                "doc_type": "README",
                "title": f"README - {repo.name}",
                "content": cls._generate_readme(repo, parsed_files)
            },
            {
                "doc_type": "ARCHITECTURE",
                "title": f"Architecture Overview - {repo.name}",
                "content": cls._generate_architecture_doc(repo, parsed_files)
            },
            {
                "doc_type": "API",
                "title": f"API Reference - {repo.name}",
                "content": cls._generate_api_doc(repo, parsed_files)
            },
            {
                "doc_type": "ONBOARDING",
                "title": f"Developer Onboarding Guide - {repo.name}",
                "content": cls._generate_onboarding_guide(repo, parsed_files)
            },
            {
                "doc_type": "CONTRIBUTING",
                "title": f"Contributing Guidelines - {repo.name}",
                "content": cls._generate_contributing_guide(repo)
            }
        ]
        return docs

    @staticmethod
    def _generate_readme(repo: Repository, files: List[ParsedFileInfo]) -> str:
        lang_badges = " ".join([f"`{k}: {v}%`" for k, v in (repo.languages or {}).items()]) or f"`{repo.primary_language}`"
        
        # Detect key entrypoints
        entrypoints = [f.rel_path for f in files if os.path.basename(f.rel_path) in ("main.py", "app.py", "index.ts", "server.js", "main.go")]
        entrypoint_text = f"`{entrypoints[0]}`" if entrypoints else "main project module"

        return f"""# {repo.name}

> {repo.description or "Automated technical documentation generated by RepoMind AI."}

## 📊 Repository Metrics

- **Primary Language:** {repo.primary_language or "Multi-language"}
- **Language Composition:** {lang_badges}
- **Indexed Files:** {repo.total_files}
- **Analyzed Lines of Code:** {repo.total_lines:,}
- **Default Branch:** `{repo.default_branch}`

---

## 🚀 Quick Start

### Prerequisites
- Git
- {repo.primary_language or "Runtime environment for this stack"}

### 1. Clone the repository
```bash
git clone {repo.url}.git
cd {repo.name}
```

### 2. Configure Environment
Check for any `.env.example` or configuration files in the root directory and set required parameters.

### 3. Run the Application
Launch via the primary entrypoint: {entrypoint_text}.

---

## 📂 Core Project Structure

| File / Directory | Language | Lines | Description |
| :--- | :--- | :--- | :--- |
""" + "\n".join([
    f"| `{f.rel_path}` | {f.language} | {f.line_count} | {len(f.functions)} functions, {len(f.classes)} classes |"
    for f in files[:15]
]) + f"""

---

## 🛡️ Security & Quality Audits
Analyzed with static code analysis and semantic vector indexing via **RepoMind AI**.
"""

    @staticmethod
    def _generate_architecture_doc(repo: Repository, files: List[ParsedFileInfo]) -> str:
        # Group files
        routes = [f for f in files if "api" in f.rel_path.lower() or "route" in f.rel_path.lower()]
        models = [f for f in files if "model" in f.rel_path.lower() or "schema" in f.rel_path.lower() or "db" in f.rel_path.lower()]
        services = [f for f in files if "service" in f.rel_path.lower() or "core" in f.rel_path.lower() or "lib" in f.rel_path.lower()]

        return f"""# Architecture Guide: {repo.name}

## 🏛️ System Overview

The **{repo.name}** repository is structured as a modular {repo.primary_language or 'multi-language'} application. 

```mermaid
graph TD
    Client[Client / Consumer] --> Entrypoint[Application Entrypoint]
    Entrypoint --> API[Routing & API Layer]
    API --> Services[Business Services]
    Services --> DB[Data Layer / Models]
```

## 🧩 Architectural Layers

### 1. Routing & Interface Layer
Handles incoming requests, parameters validation, and HTTP/RPC responses:
""" + "\n".join([f"- `{f.rel_path}` ({len(f.functions)} endpoints/handlers)" for f in routes[:8]] or ["- *Standard module entrypoints*"]) + f"""

### 2. Business Logic & Services Layer
Encapsulates domain logic, external integrations, and orchestrations:
""" + "\n".join([f"- `{f.rel_path}` ({f.line_count} LOC)" for f in services[:8]] or ["- *Direct procedural or functional service modules*"]) + f"""

### 3. Data Storage & Entity Models
Data definitions, schema validations, and database abstractions:
""" + "\n".join([f"- `{f.rel_path}` ({len(f.classes)} entities)" for f in models[:8]] or ["- *Configuration-driven data structures*"]) + f"""

## 🔄 Dependency Management
The project utilizes automated modular imports, maintaining separation of concerns between schema declarations and business execution.
"""

    @staticmethod
    def _generate_api_doc(repo: Repository, files: List[ParsedFileInfo]) -> str:
        api_files = [f for f in files if any(k in f.rel_path.lower() for k in ("api", "route", "controller", "endpoint"))]
        if not api_files:
            api_files = files[:5]

        items = []
        for f in api_files:
            for fn in f.functions:
                items.append(f"### `{fn.name}()`\n- **File:** `{f.rel_path}:{fn.start_line}`\n- **Language:** {f.language}\n")

        endpoints_str = "\n".join(items[:20]) if items else "No explicitly exported API functions detected in analyzed files."

        return f"""# API & Function Reference: {repo.name}

## Analyzed Handlers and Functions

{endpoints_str}
"""

    @staticmethod
    def _generate_onboarding_guide(repo: Repository, files: List[ParsedFileInfo]) -> str:
        return f"""# New Developer Onboarding Guide

Welcome to **{repo.name}**! This document accelerates your ramp-up time to help you make your first contribution within 48 hours.

## 🎯 1. First Day Checklist
- [ ] Clone repository: `git clone {repo.url}.git`
- [ ] Inspect repository structure and check out the `{repo.default_branch}` branch.
- [ ] Review environment requirements for {repo.primary_language}.
- [ ] Run test suite to verify baseline functionality.

## 🗺️ 2. Codebase Walkthrough
- **Entry point:** Identify top-level files (`main`, `app`, `server`).
- **Core modules:** Located across {len(files)} indexed source files.
- **Architectural boundaries:** Strictly observe layers between routes, business logic, and schemas.

## 🧪 3. Running Tests
Verify your local setup before submitting changes:
```bash
# Execute local unit and integration tests
# (e.g. pytest, npm test, cargo test, or go test)
```

## 💡 4. Need Help?
Use **RepoMind AI Chat** to ask context-aware questions directly against the indexed codebase!
"""

    @staticmethod
    def _generate_contributing_guide(repo: Repository) -> str:
        return f"""# Contributing to {repo.name}

Thank you for your interest in contributing to **{repo.name}**!

## 🔀 Branching Strategy
- Branch from `{repo.default_branch}` using descriptive branch names:
  - `feat/feature-name`
  - `fix/bug-description`
  - `docs/documentation-update`

## 📝 Pull Request Guidelines
1. Ensure all new code has accompanying tests.
2. Maintain clean architecture and avoid circular dependencies.
3. Keep PRs focused on a single responsibility.
4. Verify all tests pass before requesting review.

Thank you for helping improve {repo.name}!
"""
